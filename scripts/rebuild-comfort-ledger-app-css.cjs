#!/usr/bin/env node
/**
 * Regenerates comfort-ledger-app.FULL-BACKUP.css — single-file CSS equivalent to
 * comfort-ledger-critical.css + charts + animations (#9 split), in original cascade order.
 * Run: node scripts/rebuild-comfort-ledger-app-css.cjs
 *
 * Roll back to one stylesheet: copy FULL-BACKUP to comfort-ledger-app.css, point HTML/SW/PRECACHE there, remove deferred links if you want blocking single file again.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "..");

function stripBanner(text) {
  return text.replace(/^\/\*[\s\S]*?\*\/\s*\n?/, "");
}

const critical = stripBanner(fs.readFileSync(path.join(dir, "comfort-ledger-critical.css"), "utf8")).split("\n");
const chartsRaw = stripBanner(fs.readFileSync(path.join(dir, "comfort-ledger-charts.css"), "utf8")).split("\n");
const animations = stripBanner(fs.readFileSync(path.join(dir, "comfort-ledger-animations.css"), "utf8")).split("\n");

/** Line counts match the split in #9 — keep in sync if you change sliced files manually. */
const L = Object.freeze({
  segA: 152,
  segB: 1265 - 183 + 1,
  segC: 1823 - 1466 + 1,
  segD: 2195 - 1888 + 1,
  ch1: 1465 - 1266 + 1,
  ch2: 1887 - 1824 + 1,
  ch3: 2636 - 2196 + 1
});

let i = 0;
function take(arr, n) {
  const out = arr.slice(i, i + n);
  i += n;
  return out;
}

const segA = take(critical, L.segA);
const segB = take(critical, L.segB);
const segC = take(critical, L.segC);
const segD = take(critical, L.segD);
const segE = critical.slice(i);
i = critical.length;

let j = 0;
function takeCh(arr, n) {
  const out = arr.slice(j, j + n);
  j += n;
  return out;
}
const ch1 = takeCh(chartsRaw, L.ch1);
const ch2 = takeCh(chartsRaw, L.ch2);
const ch3 = takeCh(chartsRaw, L.ch3);

while (j < chartsRaw.length && chartsRaw[j] === "") j++;
if (j !== chartsRaw.length) {
  console.error(`charts: leftover lines after ch3 (${chartsRaw.length - j})`);
  process.exit(1);
}

function expect(name, actual, wanted) {
  if (actual !== wanted) {
    console.error(`${name}: got ${actual}, want ${wanted}`);
    process.exit(1);
  }
}

expect("segA", segA.length, L.segA);
expect("segB", segB.length, L.segB);
expect("segC", segC.length, L.segC);
expect("segD", segD.length, L.segD);
expect("ch1", ch1.length, L.ch1);
expect("ch2", ch2.length, L.ch2);
expect("ch3", ch3.length, L.ch3);

const banner =
  "/* Single-file rollup of #9 split. Regenerated by scripts/rebuild-comfort-ledger-app-css.cjs */\n";

const monolith =
  banner +
  [
    "",
    ...segA,
    ...animations,
    ...segB,
    ...ch1,
    ...segC,
    ...ch2,
    ...segD,
    ...ch3,
    ...segE,
    ""
  ].join("\n");

const outPath = path.join(dir, "comfort-ledger-app.FULL-BACKUP.css");
fs.writeFileSync(outPath, monolith);
console.log("Wrote", outPath, `(${Math.round(Buffer.byteLength(monolith) / 1024)} KB)`);
